// Builds src/js/globe/land.js: Fibonacci-lattice land bitsets for each tier,
// plus a fine grid of points inside the UK for the amber highlight.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const land = feature(JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json')), 'land');
const countries = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json'));
const uk = feature(countries, countries.objects.countries).features.find((f) => f.properties.name === 'United Kingdom');

function bitset(n) {
  const bits = new Uint8Array(Math.ceil(n / 8));
  const golden = Math.PI * (3 - Math.sqrt(5));
  let count = 0;
  for (let i = 0; i < n; i++) {
    const y = 1 - (i / (n - 1)) * 2;
    const lat = Math.asin(y) * 180 / Math.PI;
    const lon = ((((i * golden) * 180 / Math.PI) % 360) + 540) % 360 - 180;
    if (lat < -60) continue; // leave Antarctica out: keeps the globe readable
    if (geoContains(land, [lon, lat]) && !geoContains(uk, [lon, lat])) { bits[i >> 3] |= 1 << (i & 7); count++; }
  }
  return { b64: Buffer.from(bits).toString('base64'), count };
}

const ukPts = [];
for (let lat = 49.8; lat <= 60.9; lat += 0.32) {
  for (let lon = -8.3; lon <= 1.9; lon += 0.32 / Math.cos(lat * Math.PI / 180) * 0.9) {
    if (geoContains(uk, [lon, lat])) ukPts.push(+lat.toFixed(2), +lon.toFixed(2));
  }
}
const enhanced = bitset(26000);
const simplified = bitset(11000);
writeFileSync('src/js/globe/land.js', `// Generated by tools/gen-land.mjs from Natural Earth 50m (world-atlas). Do not edit.
export const LAND = { enhanced: { n: 26000, bits: '${enhanced.b64}' }, simplified: { n: 11000, bits: '${simplified.b64}' } };
export const UK = [${ukPts.join(',')}];
`);
console.log('enhanced dots', enhanced.count, 'simplified', simplified.count, 'uk', ukPts.length / 2);

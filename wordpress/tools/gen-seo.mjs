// Generates two PHP data files for the plugin from the static site's HTML pages:
// - includes/seo.php: title, meta description, Open Graph tags and JSON-LD blocks, keyed by page slug.
// - includes/alt-text.php: alt text of each <picture> photo, keyed by image base name.
// Usage: node tools/gen-seo.mjs [distDir] [pluginDir]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(process.argv[2] || join(here, '..', '..', 'dist'));
const plugin = resolve(process.argv[3] || join(here, '..', 'learn-uk-site'));

const LIVE = /^https?:\/\/(www\.)?learnuk\.co\.uk\/?/i;
const decode = (s) => s
  .replace(/&quot;/g, '"').replace(/&#39;|&#x27;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&amp;/g, '&');
const slugOf = (file) => (file === 'index.html' ? 'home' : file.replace(/\.html$/, ''));
const php = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// Page links (about.html, /faqs.html#x, live-site URLs) become https://lu.home/ placeholders,
// which the plugin swaps for the real home URL when it prints the JSON-LD.
function toPlaceholder(value) {
  let v = value.replace(LIVE, '');
  const m = v.match(/^\/?([\w-]+)\.html([?#].*)?$/);
  if (m) return `https://lu.home/${m[1] === 'index' ? '' : `${m[1]}/`}${m[2] || ''}`;
  if (v !== value) return `https://lu.home/${v}`;
  return value;
}
const mapStrings = (node) => {
  if (typeof node === 'string') return toPlaceholder(node);
  if (Array.isArray(node)) return node.map(mapStrings);
  if (node && typeof node === 'object') return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, mapStrings(v)]));
  return node;
};

const files = readdirSync(dist).filter((f) => f.endsWith('.html')).sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : a.localeCompare(b)));
const pages = {};
const alts = {};
for (const file of files) {
  const html = readFileSync(join(dist, file), 'utf8');
  const head = html.split('</head>')[0];
  // First alt seen for each photo wins (home page first); differing alts are reported.
  for (const [pic] of html.matchAll(/<picture\b[\s\S]*?<\/picture>/g)) {
    const img = (pic.match(/<img\b[^>]*>/) || [''])[0];
    const src = (img.match(/\bsrc="([^"]*)"/) || [])[1];
    if (!src) continue;
    const base = src.split('/').pop().replace(/\.\w+$/, '').replace(/-\d+$/, '');
    const alt = decode((img.match(/\balt="([^"]*)"/) || [])[1] || '');
    if (!(base in alts)) alts[base] = alt;
    else if (alts[base] !== alt) console.warn(`alt variant for ${base} in ${file}: "${alt}" (kept "${alts[base]}")`);
  }
  const meta = (attr, name) => {
    const m = head.match(new RegExp(`<meta ${attr}="${name}" content="([^"]*)"`));
    return m ? decode(m[1]) : '';
  };
  const og = {};
  for (const m of head.matchAll(/<meta property="(og:[\w:]+)" content="([^"]*)"/g)) {
    if (m[1] !== 'og:url') og[m[1]] = decode(m[2]);
  }
  const jsonld = [...head.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)]
    .map((m) => JSON.stringify(mapStrings(JSON.parse(m[1]))));
  pages[slugOf(file)] = {
    title: decode((head.match(/<title>([^<]*)<\/title>/) || [])[1] || ''),
    description: meta('name', 'description'),
    og,
    jsonld,
  };
}

const lines = [
  '<?php',
  '/**',
  ' * Head metadata for the Learn UK pages, keyed by page slug.',
  ' *',
  ' * Generated by tools/gen-seo.mjs from the static site. Do not edit by hand.',
  ' *',
  ' * @package Learn_UK_Site',
  ' */',
  '',
  "defined( 'ABSPATH' ) || exit;",
  '',
  'return array(',
];
for (const [slug, p] of Object.entries(pages)) {
  lines.push(`\t${php(slug)} => array(`);
  lines.push(`\t\t'title'       => ${php(p.title)},`);
  lines.push(`\t\t'description' => ${php(p.description)},`);
  lines.push(`\t\t'og'          => array(`);
  for (const [k, v] of Object.entries(p.og)) lines.push(`\t\t\t${php(k)} => ${php(v)},`);
  lines.push('\t\t),');
  lines.push(`\t\t'jsonld'      => array(`);
  for (const j of p.jsonld) lines.push(`\t\t\t${php(j)},`);
  lines.push('\t\t),');
  lines.push('\t),');
}
lines.push(');', '');
writeFileSync(join(plugin, 'includes', 'seo.php'), lines.join('\n'));
console.log(`Wrote ${Object.keys(pages).length} pages to includes/seo.php`);

const altLines = [
  '<?php',
  '/**',
  ' * Alt text for the Learn UK photos, keyed by image base name (no size suffix or extension).',
  ' * An empty string marks a decorative image: it stays without alt text.',
  ' *',
  ' * Generated by tools/gen-seo.mjs from the static site. Do not edit by hand.',
  ' *',
  ' * @package Learn_UK_Site',
  ' */',
  '',
  "defined( 'ABSPATH' ) || exit;",
  '',
  'return array(',
  ...Object.keys(alts).sort().map((k) => `\t${php(k)} => ${php(alts[k])},`),
  ');',
  '',
];
writeFileSync(join(plugin, 'includes', 'alt-text.php'), altLines.join('\n'));
console.log(`Wrote ${Object.keys(alts).length} images to includes/alt-text.php`);

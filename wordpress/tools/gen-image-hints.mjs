// Writes includes/image-hints.php: the `sizes` and loading priority each photo has on the static site,
// so the Media Library copies load the same image widths. Usage: node gen-image-hints.mjs <dist> <plugin>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const [dist, plugin] = process.argv.slice(2);
const hints = {};
for (const f of readdirSync(dist).filter((f) => f.endsWith('.html'))) {
  for (const [pic] of readFileSync(`${dist}/${f}`, 'utf8').matchAll(/<picture[\s\S]*?<\/picture>/g)) {
    const base = (pic.match(/assets\/img\/(?:photos\/)?([a-z0-9-]+?)-\d+\.(?:jpg|png)"/) || [])[1];
    const sizes = (pic.match(/sizes="([^"]*)"/) || [])[1];
    if (!base || !sizes || base in hints) continue;
    hints[base] = { sizes, eager: /fetchpriority="high"/.test(pic) };
  }
}
const php = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
writeFileSync(`${plugin}/includes/image-hints.php`, [
  '<?php', '/**', ' * How each Learn UK photo is sized and loaded on the page, keyed by image base name.', ' *',
  ' * Generated by tools/gen-image-hints.mjs from the static site. Do not edit by hand.', ' *', ' * @package Learn_UK_Site', ' */', '',
  "defined( 'ABSPATH' ) || exit;", '', 'return array(',
  ...Object.keys(hints).sort().map((k) => `\t${php(k)} => array( 'sizes' => ${php(hints[k].sizes)}, 'eager' => ${hints[k].eager} ),`),
  ');', ''].join('\n'));
console.log(Object.keys(hints).length, 'images');
